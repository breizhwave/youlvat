<h2 id="organisateurs">Evit an aozerien</h2>
<h3>Kevreañ</h3>
<p>Bouton <b>Aozerien</b> (dindan ar yezhoù), gant ger-tremen boutin ar skipailh. Neuze e teu war wel ar boutonoù kemmañ. Adkarget e vez ar roadennoù bep 15 eilenn ha goude pep kemm.</p>
<h3>Darvoud</h3>
<ul>
  <li><b>+ Darvoud</b> / <b>Kemmañ</b> e-kichen lañser an darvoudoù : anv, lec’h, deiziadoù, skeudenn (chomlec’h https), chomlec’hioù darempred, kenstur an nozvezh (ul lankad dre linenn, « 20:00 Digeriñ an dorioù »).</li>
  <li>Ar stern « C’hoant ho peus da reiñ un taol-dorn ? » (Steuñv, Taolenn-stur) ha testenn ar bajenn Darempred a vez kemmet war al lec’h (bouton <b>Kemmañ</b>), ur stumm dre yezh : cheñchit yezh e penn uhel ar bajenn evit skrivañ ar stumm all. Hep troidigezh e vez diskouezet ar galleg.</li>
</ul>
<h3>Postoù ha prantadoù</h3>
<ul>
  <li>Ivinell <b>Postoù &amp; prantadoù</b> : <b>+ Post</b> (anv, liv, kemennoù), goude <b>+ Prantad</b> war kartenn ar post (deiz, deroù, fin, niver a dud a zo ezhomm).</li>
  <li>Fin a-raok an deroù = ar prantad a dremen hanternoz. Deroù a-raok 6 eur = noz an deiz merket (gwelet uheloc’h).</li>
  <li>Dilemel ur post a zilam e brantadoù hag o lakadennoù (miret e roll an tennadennoù).</li>
</ul>
<h3>Lakaat ur skoazeller</h3>
<ul>
  <li>Klikit war ur prantad er steuñv. E « Lakaat ur skoazeller », skrivit un nebeud lizherennoù eus an anv, ar postel pe an niverenn bellgomz, ha goude <b>Enter</b> : lakaet eo an den hag ar reti a zistro d’ar maezienn evit kenderc’hel.</li>
  <li>Renket eo an dud hervez an eurioù steuñvet dija (ar re nebeutañ karget da gentañ) ; louedet eo ar re ac’hubet d’an eur-se. Ur c’hevred a vez merket e ruz.</li>
  <li><b>Tennañ</b> a denn an den eus ar prantad : e fichenn a chom er roll hag an tennadenn a vez miret en istor.</li>
</ul>
<h3>Roll ar skoazellerien</h3>
<ul>
  <li>Ivinell <b>Skoazellerien</b> : an holl skoazellerien, en o zouez ar re n’o deus prantad ebet (ken) (« dieub »). Klikit war un talbenn evit renkañ ; dre ziouer, an enskrivadurioù nevez da gentañ.</li>
  <li><b>+ Skoazeller</b> evit ur fichenn skrivet gant an dorn (pellgomz ha postel diret). Klikit war ul linenn evit gwelet e steuñv ; « Eilañ e steuñv » a eil e brantadoù, prest da gas dre SMS pe dre bostel.</li>
  <li><b>Ezporzhiañ CSV</b> (skoazellerien × prantadoù an darvoud) ha <b>Gwarez JSON</b> (an diaz a-bezh, an istor ivez).</li>
</ul>
<h3>Kargidi</h3>
<p>Ivinell <b>Kargidi</b> → <b>+ Karget</b> : titl, niver a dud, deskrivadur, liamm d’ar fichenn bost, prantadoù evezhiet. Un den dre linenn er stumm « anv, pellgomz, postel » (pellgomz ha postel diret, en urzh ma karit), pe « + Ouzhpennañ ur skoazeller » enskrivet dija. Ar gargidi a vez diskouezet dindan anv ar postoù er steuñv.</p>

<h2 id="jourj">An deiz D</h2>
<ul>
  <li>E panell ur prantad, pep skoazeller en deus ur statud <b>rakwelet</b>, <b>bezant</b> pe <b>ezvezant</b>. An ezvezanted ne vezont ket kontet ken er c’hargañ nag en eurioù.</li>
  <li>An <b>Taolenn-stur</b> a ro ar c’hargañ, ar plasoù da bourvezañ da gentañ, an eurioù steuñvet ha kenstur an nozvezh.</li>
  <li>Meur a aozer a c’hall labourat war un dro : an diaz a ra war-dro ar skrivadurioù kenamzer, ha biskoazh ne dremen un enskrivadur niver ar plasoù.</li>
</ul>

<h2 id="historique">Roll an tennadennoù</h2>
<p>Netra ne vez kollet pa vez tennet unan bennak. Pep tennadenn a vez eilet (anv, pellgomz, postel, prantad, statud, deiziad an enskrivañ ha deiziad an tennañ) :</p>
<ul>
  <li>skoazeller tennet eus ur prantad, pe tennet abalamour ma’z eo bet dilamet ar prantad, ar post pe an darvoud ;</li>
  <li>den tennet eus ur post karget ;</li>
  <li>fichenn skoazeller dilamet (eilenn glok, an evezhiadennoù ivez).</li>
</ul>
<p>Pelec’h e welet : e traoñ an ivinell <b>Skoazellerien</b>, « Roll an tennadennoù » (evit an darvoud dibabet, hag ar fichennoù dilamet), hag e fichenn pep skoazeller. Gwelet gant an aozerien hepken ; er gwarez JSON ivez.</p>

<h2 id="liens">Liammoù war-eeun</h2>
<p>Pep anv post, prantad pe skoazeller heuliet gant an arouez 🔗 a zo ul liamm da virout er sinedoù pe da gas. Er panelloù ez eus ur bouton « Eilskrivañ al liamm ». Al liamm d’ur skoazeller ne ziskouez e chomlec’hioù klok nemet d’an aozerien kevreet.</p>

<h2 id="technique">Evit ar skipailh teknikel</h2>
<ul>
  <li>PHP 8 + SQLite, hep staliañ : kas an teuliad dre FTP. Ar ger-tremen a vez lakaet e <code>config.php</code>.</li>
  <li>Gwarez : <b>Gwarez JSON</b> (ivinell Skoazellerien), ket un eilenn FTP eus an diaz e-pad ma vez implijet.</li>
  <li>A-raok pep lakaat enlinenn : <code>php test/run.php</code> (amprouennoù emgefreek), ha goude an argerzh e <code>test/PROCEDURE.md</code>. An teuliad <code>test/</code> n’eo ket da gas.</li>
</ul>
