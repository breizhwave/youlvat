  <li>Ho niverenn bellgomz, ho postel a-bezh hag hoc’h evezhiadennoù ne vezont gwelet nemet gant an aozerien.</li>
  <li>Chomlec’hioù ar bajenn Darempred a zo re an aozadur : foran int.</li>
