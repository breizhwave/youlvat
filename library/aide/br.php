<h2 id="benevoles">Evit ar skoazellerien</h2>
<h3>Sellet ouzh ar steuñv</h3>
<ul>
  <li>Dibabit an darvoud el lañser e penn uhel ar bajenn. Digeriñ a ra an ivinell <b>Steuñv</b> war an deiz karget ar muiañ ; cheñchit deiz gant ar boutonoù a-us d’ar gael.</li>
  <li>Daou wel : <b>Kael</b> (linenn-amzer) ha <b>Roll</b> (prantadoù strollet dre bost, dre ziouer war ar pellgomzer). Derc’het e vez soñj eus ho tibab.</li>
  <li>Liv ur prantad : <b>gwer</b> = leun, <b>orañjez</b> = tud a vank, <b>ruz</b> = den ebet.</li>
  <li>Ur prantad a grog a-raok 6 eur a zo eus noz an deiz merket : « 31 a viz Kerzu, 00:00–05:00 » eo noz an 31 d’ar 1añ.</li>
  <li>War ar pellgomzer, ar bouton melen <b>☰</b> e-kichen ar yezhoù a zigor lañser ar pajennoù.</li>
</ul>
<h3>En em enskrivañ</h3>
<ol>
  <li>Bouton <b>En em enskrivañ</b> (pe « En em enskrivañ evel skoazeller » er stern war ar steuñv).</li>
  <li>Dibabit ur prantad dieub, ha roit hoc’h anv-bihan, hoc’h anv-familh, ho niverenn bellgomz hag ho chomlec’h postel (ret eo an holl). Gallout a rit ouzhpennañ un evezhiadenn evit an aozerien.</li>
  <li>Evit meur a brantad, adkrogit gant an hevelep anv : implijet e vo en-dro ho fichenn.</li>
</ol>
<p>Nac’het e vez an enskrivadur ma’z eo leun ar prantad, ma’z oc’h warnañ dija, pe ma’z oc’h ac’hubet d’an eur-se dija.</p>
<h3>Kavout ma frantadoù</h3>
<p>E penn uhel ar Steuñv, « Kavout un enskrivadur » : skrivit hoc’h anv-bihan hag hoc’h anv-familh (« marie dupont »), pe ho postel pe ho niverenn bellgomz <b>rik</b>. « Kavout ur prantad » a glask dre bost, karget, deiz pe eur (« bar 31 22h »).</p>
<h3>Cheñch pe en em dennañ</h3>
<p>N’haller ket en em zienskrivañ enlinenn : ar bouton ruz <b>Cheñch / en em dennañ</b> a gas d’ar bajenn <b>Darempred</b> eus an darvoud.</p>
<h3>Bezañ karget</h3>
<p>Ivinell <b>Kargidi</b> : keit ha ma chom plas war ur post karget, ar bouton <b>En em ginnig a ran</b> a gas d’ur furmskrid enskrivañ. Bezañ karget ne enskriv ket ac’hanoc’h war prantadoù ar post.</p>

